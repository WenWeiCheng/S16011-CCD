/*****************************************************************************/
/**
* @brief  code → 温度（degC），查表线性插值，区间外钳位。
******************************************************************************/
static float Monitor_LookupTemp(s16 code)
{
    s32 num, den;
    u32 i;

    if ((u16)code >= g_ntc_table[0].Code) {
        return (float)g_ntc_table[0].TempX10 / 10.0f;   /* 最热端 */
    }
    if ((u16)code <= g_ntc_table[NTC_TABLE_N - 1U].Code) {
        return (float)g_ntc_table[NTC_TABLE_N - 1U].TempX10 / 10.0f; /* 最冷端 */
    }

    for (i = 0; i < NTC_TABLE_N - 1U; i++) {
        if ((u16)code <= g_ntc_table[i].Code &&
            (u16)code >  g_ntc_table[i + 1U].Code) {
            den = (s32)g_ntc_table[i + 1U].Code - (s32)g_ntc_table[i].Code;
            num = (s32)((u16)code - (s32)g_ntc_table[i].Code) *
                  (s32)(g_ntc_table[i + 1U].TempX10 - g_ntc_table[i].TempX10);
            return (float)((s32)g_ntc_table[i].TempX10 * den + num) /
                   (10.0f * (float)den);
        }
    }
    return (float)g_ntc_table[NTC_TABLE_N - 1U].TempX10 / 10.0f;
}

/*****************************************************************************/
/**
* @brief  Ads1118_Mux 枚举（0x4..0x7）→ 通道序 0..3。
******************************************************************************/
static u8 Monitor_MuxToIdx(Ads1118_Mux mux)
{
    u8 idx = (u8)mux - MONITOR_MUX_BASE;
    if (idx >= MONITOR_CHANNELS) {
        idx = 0U;
    }
    return idx;
}

/*****************************************************************************/
/**
* @brief  初始化：保存依赖实例，默认从 SENSOR_NTC 开始采样。
*
* @param  adc  ads1118 驱动实例（board_hal 已初始化）。
* @param  hb   心跳节拍源。
*
* @return XST_SUCCESS。
******************************************************************************/
int Monitor_Init(Monitor *d, Ads1118 *adc, Heartbeat *hb)
{
    Xil_AssertNonvoid(d != NULL);
    Xil_AssertNonvoid(adc != NULL);
    Xil_AssertNonvoid(hb != NULL);

    d->Adc = adc;
    d->Hb = hb;
    d->MuxIdx = 0U;
    d->LastReadMs = 0U;
    d->LastSwitchMs = 0U;
    d->Raw[0] = d->Raw[1] = d->Raw[2] = d->Raw[3] = 0;

    Ads1118_SetChannel(adc, ADS1118_MUX_SENSOR_NTC);
    return XST_SUCCESS;
}

/*****************************************************************************/
/**
* @brief  主循环节拍：每 8ms 换通道、每 2ms 读当前通道原始码入缓存。
******************************************************************************/
void Monitor_Tick(Monitor *d)
{
    u32 tick = Heartbeat_GetTick(d->Hb);

    if (tick - d->LastSwitchMs >= 8U) {
        d->LastSwitchMs = tick;
        d->MuxIdx = (u8)((d->MuxIdx + 1U) & (MONITOR_CHANNELS - 1U));
        Ads1118_SetChannel(d->Adc,
                           (Ads1118_Mux)(MONITOR_MUX_BASE + d->MuxIdx));
    }

    if (tick - d->LastReadMs >= 2U) {
        s16 raw;
        d->LastReadMs = tick;
        if (Ads1118_ReadRaw(d->Adc, &raw) == XST_SUCCESS) {
            d->Raw[d->MuxIdx] = raw;
        }
    }
}

/*****************************************************************************/
/**
* @brief  某通道最近一次原始码。
******************************************************************************/
s16 Monitor_GetRaw(Monitor *d, Ads1118_Mux mux)
{
    return d->Raw[Monitor_MuxToIdx(mux)];
}

/*****************************************************************************/
/**
* @brief  某通道换算电压（V）。
*
* V = code × FS / 2^15，单端半量程，FS = ADS1118_FS_VOLT。
******************************************************************************/
float Monitor_GetVoltage(Monitor *d, Ads1118_Mux mux)
{
    s16 code = d->Raw[Monitor_MuxToIdx(mux)];
    return (float)code * ADS1118_FS_VOLT / 32768.0f;
}

/*****************************************************************************/
/**
* @brief  NTC 通道换算温度（degC）。非 NTC 通道无意义。
******************************************************************************/
float Monitor_GetNtcTemp(Monitor *d, Ads1118_Mux mux)
{
    return Monitor_LookupTemp(d->Raw[Monitor_MuxToIdx(mux)]);
}
